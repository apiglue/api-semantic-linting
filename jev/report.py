#!/usr/bin/env python3
"""Build the Jev gate's pull-request comment from the per-spec scoring results.

Usage:
  report.py REVIEW_DIR

Reads REVIEW_DIR/specs.txt and, for the Nth spec, REVIEW_DIR/result-N.json (from
semantic_score.py) or REVIEW_DIR/error-N.txt (when the spec could not be scored).
Writes REVIEW_DIR/comment.md and prints the gate outputs as key=value lines.
"""

import json
import os
import sys
import time

MARKER = "<!-- openapi-semantic-lint-gate-jev -->"
RULES = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "rules.json")))

# GitHub comments cap at 65536 characters.
MAX_COMMENT = 60000


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def spec_section(spec: str, result: dict | None, error: str | None) -> list[str]:
    lines = [f"### {spec}", ""]
    if result is None:
        reason = " ".join((error or "no result was produced.").split())
        lines.append(f"⚠️ Could not be scored: `{reason[:500]}`")
        return lines

    fired = [r for r in result["rules"] if r["fired"]]
    if not fired:
        lines.append("No findings — the specification passed semantic review.")
        return lines

    lines += [
        "| Rule | Location | Recommendation | Severity | Rationale | Probability |",
        "|------|----------|----------------|----------|-----------|-------------|",
    ]
    for r in fired:
        rule = RULES[r["rule"]]
        lines.append(
            f"| {r['rule']} | {cell(rule['location'])} | {cell(rule['recommendation'])} "
            f"| {r['severity']} | {cell(rule['rationale'])} | {r['normalized']:.2f} |"
        )
    errors = sum(r["severity"] == "error" for r in fired)
    lines += ["", f"**Errors (must adopt):** {errors} · **Warnings (optional):** {len(fired) - errors} · "
                  f"**Compliance:** {result['compliance']:.3f}"]
    return lines


def main() -> None:
    review_dir = sys.argv[1]
    with open(os.path.join(review_dir, "specs.txt")) as f:
        specs = [line.strip() for line in f if line.strip()]

    sections = []
    errors = warnings = skipped = 0
    model = None
    for i, spec in enumerate(specs, start=1):
        result = error = None
        result_path = os.path.join(review_dir, f"result-{i}.json")
        error_path = os.path.join(review_dir, f"error-{i}.txt")
        if os.path.exists(result_path):
            with open(result_path) as f:
                result = json.load(f)
            model = model or result.get("model")
            errors += len(result["errors_fired"])
            warnings += len(result["warnings_fired"])
        else:
            skipped += 1
            if os.path.exists(error_path):
                with open(error_path) as f:
                    error = f.read().strip()
        sections += spec_section(spec, result, error) + [""]

    passed = errors == 0 and skipped == 0
    if passed and warnings:
        verdict = f"✅ **Passed** — 0 errors, {warnings} warning(s). Warnings are advisory and do not block the merge."
    elif passed:
        verdict = "✅ **Passed** — no semantic findings."
    elif skipped:
        verdict = "❌ **Blocked** — at least one specification could not be scored. See the run log."
    else:
        verdict = (f"❌ **Blocked** — {errors} error(s), {warnings} warning(s). Gate fails on: `errors`.\n\n"
                   "Resolve the errors below and push again.")

    lines = [MARKER, "## OpenAPI semantic lint gate (Jev)", "", verdict, ""]
    started_at = os.environ.get("STARTED_AT")
    if started_at:
        elapsed = int(time.time()) - int(started_at)
        lines += [f"⏱️ Ran in {elapsed // 60}m {elapsed % 60:02d}s.", ""]
    reused_run = os.environ.get("REUSED_RUN")
    if reused_run:
        url = f"{os.environ.get('RUN_URL_BASE', '')}/{reused_run}"
        lines += [f"♻️ No specification changed in this push — reused the review from [run {reused_run}]({url}).", ""]
    lines += ["### Reviewed specifications", ""]
    lines += [f"- `{spec}`" for spec in specs]
    lines += ["", "# Semantic Review Report", ""] + sections
    lines.append(
        f"<sub>Generated by TypeSafe Jev (`{model or 'jev'}`) scoring the `openapi-semantic-review` catalog. "
        "Jev reports which rules fired, not where; Probability is the chance the rule matched at least once.</sub>"
    )

    comment = "\n".join(lines) + "\n"
    if len(comment) > MAX_COMMENT:
        comment = comment[:MAX_COMMENT] + "\n\n_Report truncated — see the workflow run for the full output._\n"
    with open(os.path.join(review_dir, "comment.md"), "w") as f:
        f.write(comment)

    print(f"passed={'true' if passed else 'false'}")
    print(f"error-count={errors}")
    print(f"warning-count={warnings}")
    print(f"skipped-count={skipped}")


if __name__ == "__main__":
    main()
